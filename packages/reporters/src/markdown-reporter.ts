import type { AuditResult, Reporter, Severity } from './types.js';

export class MarkdownReporter implements Reporter {
  readonly name = 'markdown';

  format(result: AuditResult): string {
    const lines: string[] = [
      '# WorldReady Audit Report',
      '',
      `**Date:** ${result.timestamp}`,
      `**Version:** ${result.version}`,
      '',
      '## Summary',
      '',
      '| Severity | Count |',
      '|----------|-------|',
      `| 🔴 Errors | ${result.stats.errors} |`,
      `| 🟡 Warnings | ${result.stats.warnings} |`,
      `| 💡 Suggestions | ${result.stats.suggestions} |`,
      '',
      `**Files scanned:** ${result.stats.filesScanned}`,
      `**Rules evaluated:** ${result.stats.rulesRan}`,
      '',
      '## Findings',
      '',
    ];

    const groups: { title: string; severity: Severity }[] = [
      { title: 'Errors', severity: 'error' },
      { title: 'Warnings', severity: 'warning' },
      { title: 'Suggestions', severity: 'suggestion' },
    ];

    if (result.findings.length === 0) {
      lines.push('No findings.');
      lines.push('');
    } else {
      for (const group of groups) {
        const items = result.findings.filter((f) => f.severity === group.severity);
        if (items.length === 0) continue;

        lines.push(`### ${group.title}`);
        for (const finding of items) {
          lines.push('');
          lines.push(`#### [${finding.ruleId}] ${finding.message}`);
          lines.push(`- **File:** ${finding.file}:${finding.line}`);
          lines.push(`- **Confidence:** ${finding.confidence}`);
          if (finding.suggestedFix) {
            lines.push(`- **Suggested fix:** ${finding.suggestedFix}`);
          }
        }
        lines.push('');
      }
    }

    lines.push('---');
    lines.push(`*Generated by WorldReady v${result.version}*`);
    lines.push('');

    return lines.join('\n');
  }
}

export const markdownReporter = new MarkdownReporter();
