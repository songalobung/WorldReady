import { describe, it, expect } from 'vitest';
import {
  JsonReporter,
  jsonReporter,
  MarkdownReporter,
  markdownReporter,
  SarifReporter,
  sarifReporter,
  ConsoleReporter,
  consoleReporter,
  allReporters,
  getReporter,
  ANSI,
  type AuditResult,
} from './index.js';

const sampleResult: AuditResult = {
  timestamp: '2026-11-12T12:00:00.000Z',
  version: '0.1.0',
  config: {
    sourceLocale: 'en',
    targetLocales: ['fr', 'de', 'ar'],
    include: ['src/**/*'],
    exclude: ['node_modules/**'],
    rules: {
      WRD001: { severity: 'error', enabled: true },
      WRD002: { severity: 'warning', enabled: true },
      WRD003: { severity: 'suggestion', enabled: true },
    },
  },
  stats: {
    errors: 1,
    warnings: 1,
    suggestions: 1,
    filesScanned: 10,
    rulesRan: 3,
  },
  findings: [
    {
      ruleId: 'WRD001',
      severity: 'error',
      confidence: 0.95,
      message: 'Hard-coded UI text',
      file: 'src/components/Header.tsx',
      line: 15,
      column: 4,
      suggestedFix: "Use t('header.title')",
    },
    {
      ruleId: 'WRD002',
      severity: 'warning',
      confidence: 0.8,
      message: 'Missing translation key "button.submit" in locale "fr"',
      file: 'locales/fr.json',
      line: 42,
      locale: 'fr',
      key: 'button.submit',
    },
    {
      ruleId: 'WRD003',
      severity: 'suggestion',
      confidence: 0.7,
      message: 'Consider using Intl.DateTimeFormat for date formatting',
      file: 'src/utils/date.ts',
      line: 8,
    },
  ],
};

const cleanResult: AuditResult = {
  timestamp: '2026-11-12T12:00:00.000Z',
  version: '0.1.0',
  config: {
    sourceLocale: 'en',
    targetLocales: ['fr'],
    include: ['src/**/*'],
    exclude: [],
    rules: {},
  },
  stats: {
    errors: 0,
    warnings: 0,
    suggestions: 0,
    filesScanned: 5,
    rulesRan: 2,
  },
  findings: [],
};

describe('JSON Reporter', () => {
  it('has the name "json"', () => {
    expect(jsonReporter.name).toBe('json');
    expect(new JsonReporter().name).toBe('json');
  });

  it('produces valid JSON that parses back to the result', () => {
    const output = jsonReporter.format(sampleResult);
    expect(typeof output).toBe('string');

    const parsed = JSON.parse(output);
    expect(parsed).toEqual(sampleResult);
  });

  it('formats with 2-space indentation', () => {
    const output = jsonReporter.format(cleanResult);
    expect(output).toBe(JSON.stringify(cleanResult, null, 2));
  });
});

describe('Markdown Reporter', () => {
  it('has the name "markdown"', () => {
    expect(markdownReporter.name).toBe('markdown');
    expect(new MarkdownReporter().name).toBe('markdown');
  });

  it('contains expected headers and finding text', () => {
    const output = markdownReporter.format(sampleResult);

    // Title and metadata headers
    expect(output).toContain('# WorldReady Audit Report');
    expect(output).toContain('**Date:** 2026-11-12T12:00:00.000Z');
    expect(output).toContain('**Version:** 0.1.0');

    // Summary table
    expect(output).toContain('## Summary');
    expect(output).toContain('| Severity | Count |');
    expect(output).toContain('| 🔴 Errors | 1 |');
    expect(output).toContain('| 🟡 Warnings | 1 |');
    expect(output).toContain('| 💡 Suggestions | 1 |');
    expect(output).toContain('**Files scanned:** 10');
    expect(output).toContain('**Rules evaluated:** 3');

    // Findings section grouped by severity
    expect(output).toContain('## Findings');
    expect(output).toContain('### Errors');
    expect(output).toContain('#### [WRD001] Hard-coded UI text');
    expect(output).toContain('- **File:** src/components/Header.tsx:15');
    expect(output).toContain('- **Confidence:** 0.95');
    expect(output).toContain("- **Suggested fix:** Use t('header.title')");

    expect(output).toContain('### Warnings');
    expect(output).toContain('#### [WRD002] Missing translation key "button.submit" in locale "fr"');
    expect(output).toContain('- **File:** locales/fr.json:42');

    expect(output).toContain('### Suggestions');
    expect(output).toContain('#### [WRD003] Consider using Intl.DateTimeFormat for date formatting');
    expect(output).toContain('- **File:** src/utils/date.ts:8');

    // Footer
    expect(output).toContain('*Generated by WorldReady v0.1.0*');
  });

  it('handles clean result without findings gracefully', () => {
    const output = markdownReporter.format(cleanResult);
    expect(output).toContain('## Findings');
    expect(output).toContain('No findings.');
    expect(output).toContain('*Generated by WorldReady v0.1.0*');
  });
});

describe('SARIF Reporter', () => {
  it('has the name "sarif"', () => {
    expect(sarifReporter.name).toBe('sarif');
    expect(new SarifReporter().name).toBe('sarif');
  });

  it('produces valid SARIF structure with correct schema version', () => {
    const output = sarifReporter.format(sampleResult);
    expect(typeof output).toBe('string');

    const sarif = JSON.parse(output);

    // Schema and version
    expect(sarif.$schema).toBe(
      'https://raw.githubusercontent.com/oasis-tcs/sarif-spec/main/sarif-2.1/schema/sarif-schema-2.1.0.json',
    );
    expect(sarif.version).toBe('2.1.0');

    // Tool driver
    expect(sarif.runs).toHaveLength(1);
    const run = sarif.runs[0];
    expect(run.tool.driver.name).toBe('WorldReady');
    expect(run.tool.driver.version).toBe('0.1.0');
    expect(run.tool.driver.rules.length).toBeGreaterThanOrEqual(3);

    // Results mapping
    expect(run.results).toHaveLength(3);

    // Error result
    const errorResult = run.results[0];
    expect(errorResult.ruleId).toBe('WRD001');
    expect(errorResult.level).toBe('error');
    expect(errorResult.message.text).toBe('Hard-coded UI text');
    expect(errorResult.locations[0].physicalLocation.artifactLocation.uri).toBe(
      'src/components/Header.tsx',
    );
    expect(errorResult.locations[0].physicalLocation.region.startLine).toBe(15);
    expect(errorResult.locations[0].physicalLocation.region.startColumn).toBe(4);

    // Warning result
    const warningResult = run.results[1];
    expect(warningResult.ruleId).toBe('WRD002');
    expect(warningResult.level).toBe('warning');

    // Suggestion result mapped to note
    const suggestionResult = run.results[2];
    expect(suggestionResult.ruleId).toBe('WRD003');
    expect(suggestionResult.level).toBe('note');
  });

  it('normalizes Windows backslashes in artifactLocation uri', () => {
    const resultWithBackslashes: AuditResult = {
      ...sampleResult,
      findings: [
        {
          ruleId: 'WRD001',
          severity: 'error',
          confidence: 1,
          message: 'Error message',
          file: 'src\\components\\Header.tsx',
          line: 10,
        },
      ],
    };

    const output = sarifReporter.format(resultWithBackslashes);
    const sarif = JSON.parse(output);
    expect(sarif.runs[0].results[0].locations[0].physicalLocation.artifactLocation.uri).toBe(
      'src/components/Header.tsx',
    );
  });
});

describe('Console Reporter', () => {
  it('has the name "console"', () => {
    expect(consoleReporter.name).toBe('console');
    expect(new ConsoleReporter().name).toBe('console');
  });

  it('contains ANSI colour codes', () => {
    const output = consoleReporter.format(sampleResult);

    // ANSI codes for colours
    expect(output).toContain(ANSI.red); // Error colour
    expect(output).toContain(ANSI.yellow); // Warning colour
    expect(output).toContain(ANSI.blue); // Suggestion colour
    expect(output).toContain(ANSI.reset); // Reset code

    // Content checks
    expect(output).toContain('WorldReady Audit Report');
    expect(output).toContain('WRD001 (error)');
    expect(output).toContain('line 15:');
    expect(output).toContain('Hard-coded UI text');

    expect(output).toContain('WRD002 (warning)');
    expect(output).toContain('WRD003 (suggestion)');

    // Footer check
    expect(output).toContain('Total: 3 issues');
  });

  it('handles clean result with passing status', () => {
    const output = consoleReporter.format(cleanResult);
    expect(output).toContain('No issues found');
    expect(output).toContain('0 issues found');
  });
});

describe('Index Exports', () => {
  it('exports allReporters array containing all 4 reporters', () => {
    expect(allReporters).toHaveLength(4);
    const names = allReporters.map((r) => r.name);
    expect(names).toEqual(['json', 'markdown', 'sarif', 'console']);
  });

  it('getReporter retrieves reporter by name', () => {
    expect(getReporter('json')).toBe(jsonReporter);
    expect(getReporter('markdown')).toBe(markdownReporter);
    expect(getReporter('sarif')).toBe(sarifReporter);
    expect(getReporter('console')).toBe(consoleReporter);
    expect(getReporter('unknown')).toBeUndefined();
  });
});
